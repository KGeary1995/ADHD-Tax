#!/usr/bin/env python3
"""Writes lib/core/theme/ph.dart: the Phosphor icons the app uses, as
const IconData on the fonts bundled in assets/fonts (Phosphor-*.ttf, MIT).

The phosphor_flutter package can't be used directly: its icon class extends
IconData, which newer Flutter makes a final class. The fonts and codepoints
are the same, so this reads the codepoints from that package's source.

Usage (from app/):
    python3 tool/make_phosphor.py [path/to/phosphor_icons_regular.dart]

The default path is phosphor_flutter 2.1.0 in the pub cache; get it with
`dart pub cache add phosphor_flutter --version 2.1.0`. To add an icon, add
its camelCase name (as on phosphoricons.com, e.g. star-four -> starFour)
to NAMES and run this again.
"""
import os
import re
import subprocess
import sys

NAMES = sorted(set("""
archive arrowClockwise arrowUpRight confetti lifebuoy quotes arrowCounterClockwise arrowElbowDownLeft arrowLeft
arrowRight arrowSquareOut arrowsInLineVertical arrowsOutSimple batteryHigh
batteryLow batteryMedium bellSimple bellSimpleRinging bellSimpleSlash
bookmarkSimple briefcase broom calendarBlank caretDown caretLeft caretRight
caretUp carSimple chartBar check checkCircle checkSquare circle clock
clockCounterClockwise cloud cloudArrowUp cloudCheck cloudSlash coins columns
copySimple devices dotsSixVertical dotsThree dotsThreeVertical downloadSimple
envelopeSimple flag flask floppyDisk gift flowerLotus folderOpen folderSimple
funnelSimple gearSix gift handHeart handWaving hash headphones hourglassMedium
houseSimple infinity info kanban keyboard lightning linkBreak linkSimple
listBullets listChecks lock magnifyingGlass mapPin medal microphone moon
moonStars note notePencil palette pause pencilSimple play plus pushPin
question repeat shareFat shieldCheck shootingStar shuffle slidersHorizontal smileyMeh
sparkle squaresFour star starFour stop sunHorizon target textAlignLeft timer
trash trophy users warningCircle x
""".split()))

FAMILIES = [('', 'PhosphorRegular'), ('Fill', 'PhosphorFill'),
            ('Bold', 'PhosphorBold')]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
        '~/.pub-cache/hosted/pub.dev/phosphor_flutter-2.1.0/lib/src/'
        'phosphor_icons_regular.dart')
    codes = dict(re.findall(
        r'static const (\w+) = PhosphorFlatIconData\((0x[0-9a-f]+)',
        open(src).read()))
    missing = [n for n in NAMES if n not in codes]
    if missing:
        sys.exit('Not in Phosphor: ' + ', '.join(missing))
    out = [
        '// Generated by tool/make_phosphor.py. Do not edit by hand.',
        '// Phosphor Icons (MIT), fonts in assets/fonts/Phosphor-*.ttf.',
        '',
        "import 'package:flutter/widgets.dart';",
        '',
        '/// Phosphor icons: Regular by default, `…Fill` for the active tab',
        '/// and stars, `…Bold` for + and checks.',
        'abstract final class Ph {',
    ]
    for n in NAMES:
        for suffix, family in FAMILIES:
            out.append(
                f"  static const {n}{suffix} = IconData({codes[n]}, "
                f"fontFamily: '{family}');")
    out.append('}')
    path = os.path.join(os.path.dirname(__file__), '..', 'lib', 'core',
                        'theme', 'ph.dart')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    try:
        subprocess.run(['dart', 'format', path], check=True,
                       capture_output=True)
    except (OSError, subprocess.CalledProcessError):
        print('Run `dart format lib` before committing.')
    print(f'Wrote {len(NAMES)} icons to {os.path.normpath(path)}')


if __name__ == '__main__':
    main()
